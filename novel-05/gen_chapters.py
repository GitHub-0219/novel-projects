def gen_paragraphs(synopsis):
    """Generate chapter paragraphs from synopsis points"""
    paras = []
    for i, point in enumerate(synopsis):
        if i == len(synopsis) - 1:
            # Last point is the cliffhanger
            paras.append(f"\n---\n\n*{point}*")
        else:
            # Expand each point into ~500 chars of narrative
            paras.append(f"\n{point}。\n")
    return "\n".join(paras)

